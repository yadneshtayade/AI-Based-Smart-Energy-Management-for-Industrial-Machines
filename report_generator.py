"""
report_generator.py – Structured JSON and PDF inspection report generation.
Generates comprehensive reports with Machine Health, Why It Happened,
What To Do Now, 4 Model Votes, and RAG Technical Document Citations.
"""

import json
import logging
import io
from datetime import datetime
from typing import Dict, Any, List, Optional

logger = logging.getLogger(__name__)


def generate_json_report(
    machine_id: str,
    sensor_readings: Dict[str, float],
    anomaly_result: Dict[str, Any],
    retrieved_docs: List[Dict],
    llm_response: Optional[str] = None,
    experiment_id: str = "N/A",
) -> Dict[str, Any]:
    ensemble_pred = anomaly_result.get("ensemble_prediction", 0)
    if hasattr(ensemble_pred, "__len__"):
        ensemble_pred = int(ensemble_pred[0]) if len(ensemble_pred) > 0 else 0
    ensemble_pred = int(ensemble_pred)

    ensemble_score = anomaly_result.get("ensemble_score", 0.0)
    if hasattr(ensemble_score, "__len__"):
        ensemble_score = float(ensemble_score[0]) if len(ensemble_score) > 0 else 0.0
    ensemble_score = float(ensemble_score)

    votes = anomaly_result.get("anomaly_votes", 0)
    if hasattr(votes, "__len__"):
        votes = int(votes[0]) if len(votes) > 0 else 0
    votes = int(votes)

    health_status = "ANOMALY DETECTED" if ensemble_pred else "NORMAL (HEALTHY)"
    health_score_pct = max(10.0, min(99.0, 100.0 - (votes * 22.5) if ensemble_pred else 96.5))

    # Evaluate physical triggers
    v1 = sensor_readings.get("Vibration1", 0.027)
    v2 = sensor_readings.get("Vibration2", 0.039)
    curr = sensor_readings.get("Current", 1.3)
    press = sensor_readings.get("Pressure", 0.05)
    temp = sensor_readings.get("Temperature", 75.5)
    flow = sensor_readings.get("FlowRate", 32.0)

    why_reasons = []
    actions = []

    if v1 > 0.08 or v2 > 0.09:
        why_reasons.append(f"Accelerometer RMS (V1: {v1:.4f}g, V2: {v2:.4f}g) significantly exceeded safe operational thresholds (0.08g). Indicates bearing outer raceway flaking, unbalance, or angular shaft misalignment.")
        actions.append("Perform laser shaft alignment check and spectral vibration FFT analysis (SKF Bearing Standard ISO 10816).")

    if curr > 2.2:
        why_reasons.append(f"Motor current ({curr:.2f}A) is drawing above nominal 2.0A threshold. Suggests heavy mechanical binding, pump rotor obstruction, or stator insulation degradation.")
        actions.append("Perform motor winding insulation resistance test (Megger) and verify terminal connection torque.")

    if press > 0.5:
        why_reasons.append(f"Discharge pressure ({press:.2f} bar) exceeds safe limit (0.45 bar), indicating line throttling, control valve blockage, or pump cavitation.")
        actions.append("Inspect downstream control valve travel and clean inline pipe suction strainers.")

    if temp > 82.0:
        why_reasons.append(f"Fluid temperature ({temp:.1f}°C) exceeded 80°C threshold, indicating heat exchanger fouling, low coolant flow, or excessive internal friction.")
        actions.append("Flush cooling heat exchanger and inspect bearing lubrication oil viscosity.")

    if flow < 25.0:
        why_reasons.append(f"Volume flow rate ({flow:.1f} L/min) dropped below design delivery, indicating pump cavitation or suction starvation.")
        actions.append("Verify pump NPSH (Net Positive Suction Head) and check suction valves.")

    if not ensemble_pred:
        why_reasons = ["All 8 telemetry channels (Vibration, Current, Pressure, Temperature, Voltage, Flow Rate) are tracking safely within design tolerances. Ensemble covariance is stable."]
        actions = ["Continue scheduled preventive monitoring. Log telemetry in the asset health database."]

    report = {
        "report_id": f"REP-{datetime.now().strftime('%Y%m%d-%H%M%S')}",
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC"),
        "machine_id": machine_id,
        "experiment_id": experiment_id,
        "health_status": health_status,
        "health_score_pct": f"{health_score_pct:.1f}%",
        "ensemble_score": round(ensemble_score, 4),
        "decision_threshold": 0.3380,
        "anomaly_votes": f"{votes} / 4 Models",
        "sensor_readings": {k: round(float(v), 4) for k, v in sensor_readings.items()},
        "why_it_happened": why_reasons,
        "what_to_do_now": actions,
        "models_breakdown": anomaly_result.get("individual_scores", {}),
        "supporting_references": [
            f"{c.get('source', 'DOE/SKF Standards')} (Page {c.get('page', '?')})"
            for c in retrieved_docs[:3]
        ] or ["DOE Motor Systems Market Assessment, p.20", "SKF Bearing Maintenance Guide, p.3"],
        "disclaimer": "This inspection report was generated by the Smart Industrial Energy AI Predictive Maintenance System. Technical recommendations require human engineering verification prior to maintenance lockout."
    }
    return report


def generate_pdf_report(report: Dict[str, Any]) -> bytes:
    """Compiles a professional ReportLab PDF inspection report."""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        )

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=A4,
            leftMargin=1.5 * cm, rightMargin=1.5 * cm,
            topMargin=1.5 * cm, bottomMargin=1.5 * cm
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "Title", parent=styles["Heading1"],
            fontName="Helvetica-Bold", fontSize=20, leading=24,
            textColor=colors.HexColor("#0a192f")
        )
        h2_style = ParagraphStyle(
            "H2", parent=styles["Heading2"],
            fontName="Helvetica-Bold", fontSize=13, leading=16,
            textColor=colors.HexColor("#0070f3"), spaceBefore=10, spaceAfter=4
        )
        body_style = ParagraphStyle(
            "Body", parent=styles["Normal"],
            fontName="Helvetica", fontSize=10, leading=14,
            textColor=colors.HexColor("#222222")
        )
        alert_style = ParagraphStyle(
            "Alert", parent=body_style,
            fontName="Helvetica-Bold", fontSize=12, leading=16,
            textColor=colors.HexColor("#ff3366") if "ANOMALY" in report.get("health_status", "") else colors.HexColor("#00aa55")
        )

        story = []

        # Header Title
        story.append(Paragraph("SMART INDUSTRIAL ENERGY AI", title_style))
        story.append(Paragraph(f"Comprehensive Machine Health & Predictive Maintenance Inspection Report", styles["Heading3"]))
        story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#0070f3"), spaceAfter=8))

        # Metadata Table
        meta_data = [
            ["Report ID:", report.get("report_id", "N/A"), "Machine Asset:", report.get("machine_id", "N/A")],
            ["Generated At:", report.get("timestamp", "N/A"), "Health Score:", report.get("health_score_pct", "N/A")],
            ["Ensemble Score:", f"{report.get('ensemble_score', 0):.4f}", "Threshold:", f"{report.get('decision_threshold', 0.338):.4f}"],
            ["Anomaly Votes:", report.get("anomaly_votes", "0/4"), "Overall Status:", report.get("health_status", "NORMAL")]
        ]
        meta_table = Table(meta_data, colWidths=[3.2*cm, 5.5*cm, 3.2*cm, 5.5*cm])
        meta_table.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f4f7fb")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#d0dbe8")),
            ("PADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 0.4 * cm))

        # Section: Sensor Readings Table
        story.append(Paragraph("1. Evaluated Sensor Telemetry & Baseline Boundaries", h2_style))
        sensor_rows = [["Sensor Channel", "Measured Value", "Normal Baseline Range", "Status"]]
        readings = report.get("sensor_readings", {})
        sensor_specs = [
            ("Vibration1", readings.get("Vibration1", 0), "0.015 – 0.080 g", "Accelerometer RMS (Radial)"),
            ("Vibration2", readings.get("Vibration2", 0), "0.015 – 0.090 g", "Accelerometer RMS (Axial)"),
            ("Current", readings.get("Current", 0), "0.50 – 2.20 A", "Motor Current Draw"),
            ("Pressure", readings.get("Pressure", 0), "-0.50 – 0.45 bar", "Hydraulic Loop Pressure"),
            ("Temperature", readings.get("Temperature", 0), "65.0 – 82.0 °C", "Fluid Core Temperature"),
            ("Thermocouple", readings.get("Thermocouple", 0), "22.0 – 31.0 °C", "Ambient Thermocouple"),
            ("Voltage", readings.get("Voltage", 0), "210.0 – 245.0 V", "AC Line Voltage"),
            ("FlowRate", readings.get("FlowRate", 0), "26.0 – 110.0 L/min", "Volumetric Delivery"),
        ]
        for name, val, safe, note in sensor_specs:
            status_text = "EXCEEDED" if (name == "Vibration1" and val > 0.08) or (name == "Current" and val > 2.2) or (name == "Pressure" and val > 0.45) or (name == "Temperature" and val > 82) or (name == "FlowRate" and val < 26) else "SAFE"
            sensor_rows.append([f"{name} ({note})", f"{val:.4f}", safe, status_text])

        sensor_table = Table(sensor_rows, colWidths=[6.5*cm, 3.5*cm, 4.5*cm, 3*cm])
        sensor_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0a192f")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(sensor_table)
        story.append(Spacer(1, 0.4 * cm))

        # Section: Why It Happened (Root Cause)
        story.append(Paragraph("2. Root Cause Analysis – Why It Has Happened", h2_style))
        for reason in report.get("why_it_happened", []):
            story.append(Paragraph(f"• {reason}", body_style))
            story.append(Spacer(1, 0.15 * cm))

        # Section: What To Do Now
        story.append(Paragraph("3. Actionable Maintenance Plan – What To Do Now & Why", h2_style))
        for idx, act in enumerate(report.get("what_to_do_now", []), 1):
            story.append(Paragraph(f"<b>Step {idx}:</b> {act}", body_style))
            story.append(Spacer(1, 0.15 * cm))

        # Section: Literature Citations
        story.append(Paragraph("4. Supporting Technical Standards & Literature Citations (RAG Knowledge Base)", h2_style))
        for ref in report.get("supporting_references", []):
            story.append(Paragraph(f"• {ref}", body_style))

        # Disclaimer
        story.append(Spacer(1, 0.4 * cm))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey))
        story.append(Paragraph(f"<i>Disclaimer: {report.get('disclaimer', '')}</i>", ParagraphStyle("Disc", parent=body_style, fontSize=7.5, textColor=colors.grey)))

        doc.build(story)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        return pdf_bytes
    except Exception as e:
        logger.error("PDF generation failed: %s", e)
        # Fallback text
        return f"Smart Industrial Energy AI Inspection Report\nMachine: {report.get('machine_id')}\nStatus: {report.get('health_status')}\nWhy: {report.get('why_it_happened')}\nWhat to do: {report.get('what_to_do_now')}".encode('utf-8')
